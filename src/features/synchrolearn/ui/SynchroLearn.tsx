// ── Toast system ──────────────────────────────────────────────────────────────

interface ToastItem { id: string; message: string; type: "success" | "error" | "info"; }

function useToasts() {
  const [toasts, setToasts] = useState<ToastItem[]>([]);
  const show = useCallback((message: string, type: ToastItem["type"] = "info") => {
    const id = crypto.randomUUID();
    setToasts((prev) => [...prev, { id, message, type }]);
    setTimeout(() => setToasts((prev) => prev.filter((t) => t.id !== id)), 4500);
  }, []);
  return { toasts, show };
}

function ToastContainer({ toasts }: { toasts: ToastItem[] }) {
  return (
    <div className="fixed top-6 right-6 z-[999] flex flex-col gap-3 pointer-events-none">
      <AnimatePresence>
        {toasts.map((t) => (
          <motion.div
            key={t.id}
            initial={{ opacity: 0, x: 40 }}
            animate={{ opacity: 1, x: 0 }}
            exit={{ opacity: 0, x: 40 }}
            className={`flex items-center gap-3 px-5 py-4 rounded-2xl text-sm font-semibold shadow-xl backdrop-blur-xl max-w-sm border ${
              t.type === "success" ? "bg-dark-card/95 border-xhosa-teal/40"
              : t.type === "error"   ? "bg-dark-card/95 border-xhosa-red/40"
              : "bg-dark-card/95 border-gold/40"
            } text-white`}
          >
            {t.type === "success" ? "✅" : t.type === "error" ? "❌" : "ℹ️"}
            {t.message}
          </motion.div>
        ))}
      </AnimatePresence>
    </div>
  );
}

