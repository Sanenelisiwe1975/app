// ── Quiz for one module ───────────────────────────────────────────────────────

interface ModuleQuizProps {
  offenderId: string;
  moduleIdx: number;
  quizTaken: boolean;
  score: number | null;
  onSubmit: (correctCount: number) => void;
  onRetake: () => void;
}

function ModuleQuiz({ offenderId, moduleIdx, quizTaken, score, onSubmit, onRetake }: ModuleQuizProps) {
  const [answers, setAnswers] = useState<Record<number, number>>({});
  const questions = SYNCHRO_MODULES[moduleIdx].questions;

  if (quizTaken && score !== null && score < 3) {
    return (
      <div className="mt-3 p-4 bg-xhosa-red/10 border border-xhosa-red/20 rounded-xl">
        <p className="text-sm text-xhosa-red font-medium mb-2">
          📊 Result: {score}/4 correct — Failed (need 3/4 to pass)
        </p>
        <button type="button" className="btn-outline-premium text-xs px-4 py-1.5" onClick={onRetake}>
          🔄 Retake Quiz
        </button>
      </div>
    );
  }

  const allAnswered = questions.every((_, qi) => answers[qi] !== undefined);

  const handleSubmit = () => {
    let correct = 0;
    questions.forEach((q, qi) => { if (answers[qi] === q.correct) correct++; });
    onSubmit(correct);
  };

  return (
    <div className="mt-3 space-y-5">
      {questions.map((q, qi) => (
        <div key={qi}>
          <p className="text-sm font-medium text-white mb-2">{qi + 1}. {q.text}</p>
          <div className="space-y-2">
            {q.options.map((opt, oi) => (
              <label
                key={oi}
                className={`flex items-center gap-3 px-4 py-2.5 rounded-xl cursor-pointer transition-all text-sm border ${
                  answers[qi] === oi
                    ? "bg-gold/15 border-gold/30 text-gold"
                    : "bg-white/5 border-white/10 text-white/80 hover:bg-white/10"
                }`}
              >
                <input
                  type="radio"
                  name={`q_${offenderId}_${moduleIdx}_${qi}`}
                  value={oi}
                  checked={answers[qi] === oi}
                  onChange={() => setAnswers((prev) => ({ ...prev, [qi]: oi }))}
                  className="sr-only"
                />
                {opt}
              </label>
            ))}
          </div>
        </div>
      ))}
      <button
        type="button"
        className="btn-premium w-full"
        onClick={handleSubmit}
        disabled={!allAnswered}
      >
        ✔ Submit Quiz
      </button>
    </div>
  );
}

// ── Single module card ────────────────────────────────────────────────────────

interface ModuleCardProps {
  offenderId: string;
  moduleIdx: number;
  passed: boolean;
  trainingSeen: boolean;
  quizTaken: boolean;
  score: number | null;
  onMarkSeen: () => void;
  onSubmit: (correctCount: number) => void;
  onRetake: () => void;
}

function ModuleCard({
  offenderId, moduleIdx, passed, trainingSeen, quizTaken, score,
  onMarkSeen, onSubmit, onRetake,
}: ModuleCardProps) {
  const mod = SYNCHRO_MODULES[moduleIdx];
  const [open, setOpen] = useState(!passed);

  return (
    <div className={`glass-card border-l-4 ${passed ? "border-l-xhosa-teal" : "border-l-white/10"}`}>
      {/* Header — always visible */}
      <button
        type="button"
        className="w-full p-5 flex items-center justify-between text-left"
        onClick={() => setOpen((o) => !o)}
      >
        <div className="flex items-center gap-3">
          {passed
            ? <CheckCircle className="w-5 h-5 text-xhosa-teal shrink-0" />
            : <BookOpen className="w-5 h-5 text-muted-foreground shrink-0" />
          }
          <div>
            <p className="text-sm font-semibold text-white">{mod.name}</p>
            <p className="text-[10px] text-muted-foreground mt-0.5">📘 JSE: {mod.jse}</p>
          </div>
        </div>
        <div className="flex items-center gap-3 shrink-0">
          {passed && <span className="text-xs font-bold text-xhosa-teal">+20 pts</span>}
          {open ? <ChevronUp className="w-4 h-4 text-muted-foreground" /> : <ChevronDown className="w-4 h-4 text-muted-foreground" />}
        </div>
      </button>

      {/* Expandable body */}
      <AnimatePresence initial={false}>
        {open && (
          <motion.div
            key="body"
            initial={{ height: 0, opacity: 0 }}
            animate={{ height: "auto", opacity: 1 }}
            exit={{ height: 0, opacity: 0 }}
            transition={{ duration: 0.22 }}
            className="overflow-hidden"
          >
            <div className="px-5 pb-5">
              {/* Training text */}
              <div className="bg-white/5 rounded-xl p-4 text-sm text-white/80 leading-relaxed mb-3">
                {mod.training}
              </div>

              {passed ? (
                <div className="flex items-center gap-2 text-xhosa-teal text-sm font-medium">
                  <CheckCircle className="w-4 h-4" /> Module passed — 20 points earned
                </div>
              ) : !trainingSeen ? (
                <button type="button" className="btn-outline-premium text-xs px-4 py-2" onClick={onMarkSeen}>
                  📖 I have read the training
                </button>
              ) : (
                <ModuleQuiz
                  offenderId={offenderId}
                  moduleIdx={moduleIdx}
                  quizTaken={quizTaken}
                  score={score}
                  onSubmit={onSubmit}
                  onRetake={onRetake}
                />
              )}
            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}

// ── Offender row ──────────────────────────────────────────────────────────────

interface OffenderRowProps {
  offender: OffenderRecord;
  isActive: boolean;
  onTrain: () => void;
  onIssueCert: () => void;
}

function OffenderRow({ offender, isActive, onTrain, onIssueCert }: OffenderRowProps) {
  const total = totalScore(offender.scores);
  const canCert = total >= 60 && !offender.certIssued;

  return (
    <motion.div
      layout
      className={`glass-card p-4 flex flex-wrap items-center justify-between gap-3 ${
        isActive ? "border border-gold/30" : ""
      }`}
    >
      <div className="flex items-center gap-3 min-w-0">
        <div className="w-9 h-9 rounded-xl bg-white/5 flex items-center justify-center shrink-0 text-sm font-bold text-muted-foreground">
          {offender.name.charAt(0)}
        </div>
        <div className="min-w-0">
          <p className="font-semibold text-white text-sm truncate">{offender.name}</p>
          <p className="text-[10px] text-muted-foreground">{offender.id} · {total}/100 pts</p>
        </div>
      </div>

      {/* Progress bar */}
      <div className="flex-1 min-w-[80px] max-w-[120px]">
        <div className="h-1.5 bg-white/10 rounded-full overflow-hidden">
          <div
            className="h-full bg-gradient-to-r from-gold to-xhosa-teal rounded-full transition-all"
            style={{ width: `${total}%` }}
          />
        </div>
      </div>

      <div className="flex items-center gap-2 shrink-0">
        {offender.certIssued && (
          <span className="text-xs font-semibold text-xhosa-teal flex items-center gap-1">
            <Award className="w-3.5 h-3.5" /> Certified
          </span>
        )}
        {canCert && (
          <button
            type="button"
            onClick={onIssueCert}
            className="px-3 py-1.5 rounded-xl bg-gold/15 border border-gold/30 text-gold text-xs font-semibold hover:bg-gold/25 transition-all"
          >
            🏆 Issue Cert
          </button>
        )}
        <button
          type="button"
          onClick={onTrain}
          className={`px-3 py-1.5 rounded-xl text-xs font-semibold transition-all ${
            isActive
              ? "bg-gold/20 border border-gold/40 text-gold"
              : "bg-white/5 border border-white/10 text-white hover:bg-white/10"
          }`}
        >
          🎯 Train
        </button>
      </div>
    </motion.div>
  );
}

