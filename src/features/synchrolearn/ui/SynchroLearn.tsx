function Confetti({ onDone }: { onDone: () => void }) {
  const COLORS = ["#D4AF37", "#F4E4A6", "#2D9C5E", "#0A4D3C", "#8B1A1A", "#1E3A5F", "#E07B39"];
  const pieces = Array.from({ length: 44 }, (_, i) => ({
    id: i,
    left: Math.random() * 100,
    color: COLORS[Math.floor(Math.random() * COLORS.length)],
    delay: Math.random() * 0.6,
    size: 7 + Math.random() * 9,
  }));

  useEffect(() => {
    const t = setTimeout(onDone, 2200);
    return () => clearTimeout(t);
  }, [onDone]);

  return (
    <>
      {pieces.map((p) => (
        <motion.div
          key={p.id}
          style={{
            position: "fixed", left: `${p.left}%`, top: -24,
            width: p.size, height: p.size, borderRadius: "50%",
            background: p.color, zIndex: 998, pointerEvents: "none",
          }}
          initial={{ y: -24, opacity: 1, rotate: 0 }}
          animate={{ y: "110vh", opacity: 0, rotate: 720 }}
          transition={{ duration: 1.5 + Math.random() * 0.8, delay: p.delay, ease: "easeIn" }}
        />
      ))}
    </>
  );
}

