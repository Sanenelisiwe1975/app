// ── Main dashboard ────────────────────────────────────────────────────────────

function SynchroDashboard() {
  const session      = useSynchroStore((s) => s.session)!;
  const offenders    = useSynchroStore((s) => s.offenders);
  const lastSync     = useSynchroStore((s) => s.lastSync);
  const logout       = useSynchroStore((s) => s.logout);
  const addOffender  = useSynchroStore((s) => s.addOffender);
  const issueCert    = useSynchroStore((s) => s.issueCert);
  const markSeen     = useSynchroStore((s) => s.markTrainingSeen);
  const submitQuiz   = useSynchroStore((s) => s.submitQuiz);
  const resetQuiz    = useSynchroStore((s) => s.resetQuiz);
  const sync         = useSynchroStore((s) => s.sync);

  const [activeId, setActiveId]         = useState<string | null>(offenders[0]?.id ?? null);
  const [certMessage, setCertMessage]   = useState<string | null>(null);
  const [reportIdx, setReportIdx]       = useState(0);
  const [addName, setAddName]           = useState("");
  const [showAddInput, setShowAddInput] = useState(false);

  const activeOffender = offenders.find((o) => o.id === activeId) ?? null;

  const totalOffenders   = offenders.length;
  const totalCompleted   = offenders.reduce((acc, o) => acc + o.scores.filter((s) => s === 20).length, 0);
  const totalCerts       = offenders.filter((o) => o.certIssued).length;

  const handleIssueCert = (id: string) => {
    const ok = issueCert(id);
    if (ok) {
      const off = offenders.find((o) => o.id === id);
      setCertMessage(`🎉 Certificate issued for ${off?.name}. Eligible for reintegration consideration.`);
      setTimeout(() => setCertMessage(null), 4000);
    } else {
      setCertMessage("Requires at least 60 points (3 modules completed).");
      setTimeout(() => setCertMessage(null), 3000);
    }
  };

  const handleAddOffender = () => {
    if (addName.trim()) {
      addOffender(addName.trim());
      setAddName("");
      setShowAddInput(false);
    }
  };

  return (
    <div className="page-container pb-24">
      {/* ── Header ──────────────────────────────────────────────────────── */}
      <div className="glass-card px-5 py-3 mb-6 flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-3">
          <div className="w-8 h-8 rounded-lg bg-gold/10 border border-gold/20 flex items-center justify-center">
            <Shield className="w-4 h-4 text-gold" />
          </div>
          <div>
            <p className="text-xs font-semibold text-gold uppercase tracking-wider">FINLIT | SAPS Social Crime Prevention</p>
          </div>
        </div>
        <div className="flex items-center gap-4 text-sm text-white/70">
          <span>
            {session.role === "commander" ? "🎖️ Provincial Commander" : "👮 SAPS Facilitator"} · {session.name}
          </span>
          <button type="button" onClick={logout} className="flex items-center gap-1.5 text-xhosa-red hover:text-red-400 transition-colors text-xs">
            <LogOut className="w-3.5 h-3.5" /> Logout
          </button>
        </div>
      </div>

      {/* ── Cert celebration banner ──────────────────────────────────────── */}
      <AnimatePresence>
        {certMessage && (
          <motion.div
            initial={{ opacity: 0, y: -12 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: -12 }}
            className="glass-card px-5 py-3 mb-4 border border-gold/30 text-sm text-gold font-medium text-center"
          >
            {certMessage}
          </motion.div>
        )}
      </AnimatePresence>

      {/* ── Stats ───────────────────────────────────────────────────────── */}
      <div className="grid grid-cols-3 gap-4 mb-6">
        {[
          { label: "Offenders Enrolled", value: totalOffenders, icon: Users },
          { label: "Modules Completed",  value: totalCompleted, icon: BookOpen },
          { label: "Certificates Issued", value: totalCerts,    icon: Award },
        ].map(({ label, value, icon: Icon }) => (
          <div key={label} className="glass-card p-4 text-center">
            <Icon className="w-4 h-4 text-gold mx-auto mb-1" />
            <p className="text-2xl font-black text-gold">{value}</p>
            <p className="text-[10px] text-muted-foreground leading-tight">{label}</p>
          </div>
        ))}
      </div>

      {/* ── Offender management ─────────────────────────────────────────── */}
      <div className="glass-card p-5 mb-6">
        <div className="flex items-center justify-between mb-4">
          <div>
            <h3 className="font-semibold text-white flex items-center gap-2">
              <Users className="w-4 h-4 text-gold" /> Offender Case Management
            </h3>
            <p className="text-xs text-muted-foreground mt-0.5">Select an offender to begin training</p>
          </div>
          <button
            type="button"
            onClick={() => setShowAddInput((v) => !v)}
            className="flex items-center gap-1.5 px-3 py-1.5 bg-white/5 border border-white/10 rounded-xl text-xs text-white hover:bg-white/10 transition-all"
          >
            <UserPlus className="w-3.5 h-3.5" /> Register
          </button>
        </div>

        {/* Add offender input */}
        <AnimatePresence>
          {showAddInput && (
            <motion.div
              initial={{ height: 0, opacity: 0 }}
              animate={{ height: "auto", opacity: 1 }}
              exit={{ height: 0, opacity: 0 }}
              className="overflow-hidden mb-4"
            >
              <div className="flex gap-2">
                <input
                  type="text"
                  value={addName}
                  onChange={(e) => setAddName(e.target.value)}
                  onKeyDown={(e) => e.key === "Enter" && handleAddOffender()}
                  placeholder="Enter offender full name"
                  className="flex-1 bg-white/5 border border-white/10 rounded-xl px-4 py-2.5 text-sm text-white placeholder:text-muted-foreground focus:outline-none focus:border-gold/40"
                />
                <button type="button" className="btn-premium px-4" onClick={handleAddOffender}>Add</button>
              </div>
            </motion.div>
          )}
        </AnimatePresence>

        <div className="space-y-3">
          <AnimatePresence>
            {offenders.map((off) => (
              <OffenderRow
                key={off.id}
                offender={off}
                isActive={off.id === activeId}
                onTrain={() => setActiveId(off.id)}
                onIssueCert={() => handleIssueCert(off.id)}
              />
            ))}
          </AnimatePresence>
        </div>
      </div>

      {/* ── Module training area ─────────────────────────────────────────── */}
      <div className="glass-card p-5 mb-6">
        <div className="flex items-center justify-between mb-4">
          <h3 className="font-semibold text-white flex items-center gap-2">
            <GraduationCap className="w-4 h-4 text-gold" /> SynchroLearn Modules
          </h3>
          <span className="text-xs text-muted-foreground bg-white/5 px-3 py-1 rounded-full">
            {activeOffender ? `👤 ${activeOffender.name}` : "Select an offender above"}
          </span>
        </div>

        {activeOffender ? (
          <div className="space-y-3">
            {SYNCHRO_MODULES.map((_, mi) => {
              const qs = activeOffender.quizState[String(mi)];
              return (
                <ModuleCard
                  key={mi}
                  offenderId={activeOffender.id}
                  moduleIdx={mi}
                  passed={activeOffender.scores[mi] === 20}
                  trainingSeen={qs?.trainingSeen ?? false}
                  quizTaken={qs?.quizTaken ?? false}
                  score={qs?.score ?? null}
                  onMarkSeen={() => markSeen(activeOffender.id, mi)}
                  onSubmit={(count) => submitQuiz(activeOffender.id, mi, count)}
                  onRetake={() => resetQuiz(activeOffender.id, mi)}
                />
              );
            })}
          </div>
        ) : (
          <p className="text-sm text-muted-foreground text-center py-8">
            Click <strong className="text-white">🎯 Train</strong> on an offender above to load their modules.
          </p>
        )}
      </div>

      {/* ── Action cards ────────────────────────────────────────────────── */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
        {/* Parole report */}
        <div className="glass-card p-5">
          <h4 className="font-semibold text-white mb-3 flex items-center gap-2">
            <FileText className="w-4 h-4 text-gold" /> Parole &amp; Reintegration Report
          </h4>
          <select
            value={reportIdx}
            onChange={(e) => setReportIdx(Number(e.target.value))}
            className="w-full bg-white/5 border border-white/10 rounded-xl px-3 py-2.5 text-sm text-white mb-3"
          >
            {offenders.map((o, i) => (
              <option key={o.id} value={i}>
                {o.name} ({totalScore(o.scores)} pts)
              </option>
            ))}
          </select>
          <button
            type="button"
            className="btn-premium w-full text-sm"
            onClick={() => openParoleReport(offenders[reportIdx], session.name)}
          >
            Generate PDF Report
          </button>
        </div>

        {/* Offline sync */}
        <div className="glass-card p-5">
          <h4 className="font-semibold text-white mb-3 flex items-center gap-2">
            <RefreshCw className="w-4 h-4 text-gold" /> Offline Data Sync
          </h4>
          <p className="text-xs text-muted-foreground mb-1">Last synchronisation:</p>
          <p className="text-sm text-white mb-3">
            {lastSync ? new Date(lastSync).toLocaleTimeString("en-ZA") : "Never"}
          </p>
          <button
            type="button"
            className="btn-outline-premium w-full text-sm mb-2"
            onClick={sync}
          >
            Sync Now
          </button>
          <p className="text-[10px] text-muted-foreground">✅ All data stored locally — works without internet</p>
        </div>

        {/* Facilitator guide */}
        <FacilitatorGuide />
      </div>
    </div>
  );
}

